/**
 * AiInsights — renders Gemini AI enrichment results.
 * Shows a non-blocking notice banner when aiEnhanced is false.
 */
export default function AiInsights({ ai, aiEnhanced, aiNotice }) {
  if (!aiEnhanced) {
    return (
      <section className="dashboard-section ai-section" aria-labelledby="ai-heading">
        <div className="section-header">
          <h2 id="ai-heading" className="section-title">AI Insights</h2>
        </div>
        <div className="ai-notice-banner" role="status">
          <div>
            <strong>AI Insights Unavailable</strong>
            <p>
              {aiNotice ||
                'Gemini AI enrichment is currently unavailable. Your plan was generated using our deterministic rules engine — all budget, timeline, and vendor data is fully accurate.'}
            </p>
          </div>
        </div>
      </section>
    );
  }

  return (
    <section className="dashboard-section ai-section" aria-labelledby="ai-heading">
      <div className="section-header">
        <h2 id="ai-heading" className="section-title">AI Insights</h2>
        <span className="ai-badge" aria-label="Generated by Gemini AI">Gemini AI</span>
      </div>

      {/* Summary */}
      {ai?.summary && (
        <div className="ai-summary festival-card">
          <p className="ai-summary-text">&ldquo;{ai.summary}&rdquo;</p>
        </div>
      )}

      {/* Theme Ideas */}
      {ai?.themeIdeas?.length > 0 && (
        <div className="ai-subsection">
          <h3 className="sub-section-title">Curated Theme Ideas</h3>
          <ul className="ai-pill-list" role="list">
            {ai.themeIdeas.map((theme, i) => (
              <li key={i} className="ai-theme-pill">{theme}</li>
            ))}
          </ul>
        </div>
      )}

      {/* Tips Grid */}
      {ai?.personalisedTips?.length > 0 && (
        <div className="ai-subsection">
          <h3 className="sub-section-title">Expert Planning Tips</h3>
          <ul className="ai-tips-list" role="list">
            {ai.personalisedTips.map((tip, i) => (
              <li key={i} className="ai-tip-item">
                <span className="ai-tip-num" aria-hidden="true">{i + 1}</span>
                <span>{tip}</span>
              </li>
            ))}
          </ul>
        </div>
      )}

      {/* Vendor Suggestions */}
      {ai?.vendorSuggestions?.length > 0 && (
        <div className="ai-subsection">
          <h3 className="sub-section-title">Vendor Guidance</h3>
          <ul className="ai-vendor-list" role="list">
            {ai.vendorSuggestions.map((vs, i) => (
              <li key={i} className="ai-vendor-item">
                <span className="ai-bullet" aria-hidden="true">◆</span>
                {vs}
              </li>
            ))}
          </ul>
        </div>
      )}

      {/* Risks */}
      {ai?.risks?.length > 0 && (
        <div className="ai-subsection">
          <h3 className="sub-section-title">Risk Mitigations</h3>
          <ul className="ai-risk-list" role="list">
            {ai.risks.map((risk, i) => (
              <li key={i} className="ai-risk-item">
                <span className="risk-indicator" aria-hidden="true">Notice:</span>
                {risk}
              </li>
            ))}
          </ul>
        </div>
      )}

      <p className="ai-disclaimer">
        * AI-generated content. Always verify vendor details and pricing independently.
      </p>
    </section>
  );
}
